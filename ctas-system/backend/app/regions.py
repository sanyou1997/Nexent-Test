"""测试地区行政区划口径（统一供识别引擎 / 种子 / 筛选项 / 统计使用）。

口径：市级 + 8 个县（市、区） + 测试高新区 = 10 个地区
  市级        —— 市本级（市政府各部门、市属单位等）
  测试区一 / 测试区二 / 测试区三 / 测试区四
  测试县一 / 测试县二 / 测试县三 / 测试县四
  测试高新区

说明：本系统为通用演示系统，地区口径采用中性占位命名（测试市 / 测试区N /
测试县N / 测试高新区），不再绑定任何真实行政区划。识别引擎按同样的占名词
片段归一到 10 个标准地区之一，保证「地区」维度是可直接用于分析的稳定口径。
"""

# 10 个地区（顺序即前端筛选项与统计展示顺序）
REGIONS: list[str] = [
    "市级",
    "测试区一",
    "测试区二",
    "测试区三",
    "测试区四",
    "测试县一",
    "测试县二",
    "测试县三",
    "测试县四",
    "测试高新区",
]

# 识别用的地名片段 → 归属地区
# 值为空表示「市级」（市本级单位）
_REGION_PATTERNS: list[tuple[str, str]] = [
    # 高新区优先匹配（文中可能同时出现"测试市"与"测试高新区"）
    ("测试高新区", "测试高新区"),
    # 8 个县区（占位命名，片段即标准名，命中即归一到自身）
    ("测试区一", "测试区一"),
    ("测试区二", "测试区二"),
    ("测试区三", "测试区三"),
    ("测试区四", "测试区四"),
    ("测试县一", "测试县一"),
    ("测试县二", "测试县二"),
    ("测试县三", "测试县三"),
    ("测试县四", "测试县四"),
]

# 市级识别关键词（命中即判为市级）
_CITY_LEVEL_HINTS = [
    "市本级", "市直", "市级", "市直单位", "市直部门", "市政府",
    "市财政局", "市审计局", "市统计局", "市市场监管局", "市住建局",
    "市公安局", "市民政局", "市人社局", "市农业农村局", "市交通运输局",
    "市水利局", "市卫健局", "市教育局", "市科技局", "市工业和信息化局",
    "市生态环境局", "市应急管理局", "市城管局", "市国资局", "市退役军人事务局",
    "市政务服务和数据管理局", "市自然资源局", "市国资委", "市供销社",
    "市住房公积金", "市投资促进中心", "市公路事务中心",
]


def normalize_region(raw: str) -> str:
    """把任意地区写法归一到 10 个标准地区之一；无法归一时返回空串。"""
    s = (raw or "").strip()
    if not s:
        return ""
    if s in REGIONS:
        return s
    for frag, reg in _REGION_PATTERNS:
        if frag in s:
            return reg
    # 市级关键词
    for kw in _CITY_LEVEL_HINTS:
        if kw in s:
            return "市级"
    if "测试市" in s:
        return "市级"
    return ""


def detect_region(text: str) -> str:
    """从报告全文识别所属地区（测试市 10 区划口径）。

    规则：县区名命中优先于市级（县级报告全文常出现"测试市审计局"落款，
    不能因此误判为市级）；命中多个县区时取出现次数最多者。
    """
    t = text or ""
    if not t:
        return ""
    best_reg, best_n = "", 0
    for frag, reg in _REGION_PATTERNS:
        n = t.count(frag)
        if n > best_n:
            best_reg, best_n = reg, n
    if best_reg:
        return best_reg
    # 未命中具体县区 → 看是否市级
    if any(kw in t for kw in _CITY_LEVEL_HINTS):
        return "市级"
    if "测试市" in t:
        return "市级"
    return ""
