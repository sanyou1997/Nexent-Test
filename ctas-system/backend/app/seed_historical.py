def _index_text(r: HistoricalReport) -> str:
    return " ".join([r.title or "", r.report_type or "", r.audited_org or "", r.region or "",
                     r.problem_category or "", r.subject or "", " ".join(r.tags or []),
                     r.findings or "", r.conclusion or ""])


def _build_content(row) -> str:
    """按真实审计报告结构拼装正文（使导入后「问题发现/处理意见」段落抽取有真实语境）。"""
    (no, title, rtype, date, region, org, atype, pcat, sev, amt, subject,
     org_type, scope, good, focus, findings, conclusion, tags, refs) = row
    year = date[:4]
    return _BODY_TPL.format(
        title=title, no=no, org=org, org_type=org_type, year=year, scope=scope,
        amount=f"{amt:.1f}" if amt else "0", good=good, focus=focus,
        findings=findings.format(year=year), conclusion=conclusion, date=_cn_date(date),
    )


def _cn_date(iso: str) -> str:
    """2024-05-18 → 2024年5月18日"""
    try:
        y, m, d = iso.split("-")
        return f"{y}年{int(m)}月{int(d)}日"
    except Exception:
        return iso


def run(db, operator_id: int = 4) -> int:
    """写入历史报告演示语料。表非空则跳过（幂等）。返回写入条数。"""
    if db.query(HistoricalReport).count() > 0:
        return 0
    for row in HIST_REPORTS:
        (no, title, rtype, date, region, org, atype, pcat, sev, amt, subject,
         org_type, scope, good, focus, findings, conclusion, tags, refs) = row
        content = _build_content(row)
        r = HistoricalReport(
            report_no=no, title=title, report_type=rtype, report_date=date,
            year=int(date[:4]), region=region, audited_org=org, audit_type=atype,
            problem_category=pcat, severity=sev, amount=amt, subject=subject,
            findings=findings.format(year=date[:4]),
            conclusion=conclusion,
            legal_refs=refs, tags=tags,
            content=content, char_count=len(content), page_count=6,
            file_name="", file_type="", file_path="", content_hash="",
            extract_confidence=1.0, missing_fields=[], status="已入库",
            source="演示种子", uploaded_by=operator_id,
        )
        r.tf_vector = embeddings.embed_local(_index_text(r))
        db.add(r)
        db.flush()
        # 问题条目拆条（与批量导入管线同一套逻辑，保证统计口径一致）
        for f in split_findings(content):
            db.add(ReportFinding(
                report_id=r.id, seq=f.get("seq", ""), title=f.get("title", "")[:200],
                content=f.get("content", ""), amount=f.get("amount", 0.0),
                problem_type=f.get("problem_type", ""), severity=f.get("severity", ""),
                legal_refs=f.get("legal_refs", []) or [],
            ))
    db.commit()
    if db.query(ImportBatch).count() == 0:
        db.add(ImportBatch(batch_no="IMP20260101001", total=len(HIST_REPORTS),
                           ok=len(HIST_REPORTS), duplicated=0, failed=0, need_review=0,
                           detail_json=json.dumps(
                               [{"file": r[1], "status": "成功", "report_id": i + 1, "note": "演示种子数据"}
                                for i, r in enumerate(HIST_REPORTS)], ensure_ascii=False),
                           note="系统预置演示语料", created_by=operator_id))
        db.commit()
    return len(HIST_REPORTS)
