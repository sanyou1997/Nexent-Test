# 段落结尾允许的收尾字符（无标点也算合规的例外）
_END_OK = "。！？；：…”’》）】%％一二三四五六七八九十0123456789"
_HEADING_RE = re.compile(r"^([一二三四五六七八九十]+、|[（(][一二三四五六七八九十]+[)）]|\d+[.、]|[#＃])")
_CN = "\u4e00-\u9fff"


def check_typos(text: str, locate: str = "", protected: list | None = None) -> list[dict]:
    """错别字检查：词典精确匹配 + 上下文规则。返回带段内偏移（start/end）。

    protected: 用户自定义受保护关键词（白名单）列表；其覆盖区间内的精确词典命中将被跳过，
    避免重复误报领域常用词（用户已在界面标注这些写法为正确）。
    """
    items = []
    # 受保护关键词覆盖区间（命中则跳过）
    skip = []
    for kw in (protected or []):
        if not kw:
            continue
        start = 0
        while True:
            i = text.find(kw, start)
            if i < 0:
                break
            skip.append((i, i + len(kw)))
            start = i + len(kw)

    def _protected(s: int, e: int) -> bool:
        return any(s < b and e > a for a, b in skip)

    for wrong, right in TYPO_PAIRS:
        start = 0
        while True:
            i = text.find(wrong, start)
            if i < 0:
                break
            if not _protected(i, i + len(wrong)):
                ctx = text[max(0, i - 10):i + len(wrong) + 10]
                items.append({
                    "level": "error", "category": "错别字", "locate": locate,
                    "message": f"疑似错别字「{wrong}」应为「{right}」",
                    "context": ctx.strip(), "start": i, "end": i + len(wrong),
                })
            start = i + len(wrong)
    for pat, right, note in TYPO_CONTEXT_RULES:
        for m in pat.finditer(text):
            items.append({
                "level": "warn", "category": "规范表述", "locate": locate,
                "message": f"「{m.group(0)}」：{note}",
                "context": text[max(0, m.start() - 10):m.end() + 10].strip(),
                "start": m.start(), "end": m.end(),
            })
    return items


def check_nlp_typos(text: str, locate: str = "", covered: set | None = None,
                    protected: list | None = None) -> list[dict]:
    """离线高精度错别字检测（app.csc：混淆集 + 短语级保护），作为精确词典的补充层。

    仅做「疑似」提示（warn 级），确定性高频词仍由上面的精确词典以 error 给出。
    covered: 已被精确词典命中的 (start,end) 区间集合，命中位置跳过，避免重复报警。
    protected: 用户自定义受保护关键词（额外短语），命中区间跳过，避免重复命中领域常用词。
    """
    try:
        from app import csc
    except Exception:
        return []
    try:
        hits = csc.detect(text, protected=protected, covered=covered)
    except Exception:
        return []
    items = []
    for h in hits:
        s, e = h["start"], h["end"]
        items.append({
            "level": "warn", "category": "错别字(智能)", "locate": locate,
            "message": (f"疑似错别字「{h['wrong']}」可能应为「{h['right']}」"
                        f"（{h['source']}：替换后成词「{h['word']}」，流畅度提升{h['score']}），建议核对"),
            "context": text[max(0, s - 10):e + 10].strip(),
            "start": s, "end": e,
        })
    return items


def check_punct(text: str, locate: str = "", is_paragraph: bool = True) -> list[dict]:
    """标点符号检查（针对一个段落/单元格的文本）。"""
    items = []

    def add(level, message, context="", start=-1, end=-1):
        items.append({"level": level, "category": "标点符号", "locate": locate,
                      "message": message, "context": context, "start": start, "end": end})

    # 1. 中文语境中的英文标点
    for m in re.finditer(rf"[{_CN}]\s*([,;:?!])\s*[{_CN}]", text):
        mark = m.group(1)
        table = {",": "，", ";": "；", ":": "：", "?": "？", "!": "！"}
        add("error", f"中文语句中使用了英文标点「{mark}」，应为「{table[mark]}」",
            text[max(0, m.start() - 8):m.end() + 8], m.start(), m.end())
    for m in re.finditer(rf"[{_CN}]([.])\s*(?:[{_CN}]|$)", text):
        add("error", "中文语句中使用了英文句点「.」，应为「。」",
            text[max(0, m.start() - 8):m.end() + 8], m.start(), m.end())
    for m in re.finditer(r'"[^"\n]{1,40}"', text):
        add("warn", "使用了英文双引号，中文文书应使用中文引号“…”",
            m.group(0)[:40], m.start(), m.end())

    # 2. 标点堆叠
    for m in re.finditer(r"([，。；：、！？])\1+", text):
        add("error", f"标点重复「{m.group(0)}」，应只保留一个", m.group(0), m.start(), m.end())
    for m in re.finditer(r"[。；：][，]|[，][。；：]", text):
        add("warn", f"标点堆叠「{m.group(0)}」，请检查是否多打", m.group(0), m.start(), m.end())

    # 3. 省略号写法
    for m in re.finditer(r"\.{2,}", text):
        add("warn", "英文句点作省略号，规范写法为「……」（六个点）", m.group(0), m.start(), m.end())
    for m in re.finditer(r"…(?!…)", text[: -1]):
        add("warn", "单个「…」不规范，省略号应为「……」", "…", m.start(), m.end())
        break

    # 4. 配对符号（引号/书名号/括号）—— 无精确位置，指向该段末
    tail = len(text)
    if text.count("“") != text.count("”"):
        add("error", f"双引号不配对（“{text.count('“')}个 vs ”{text.count('”')}个），请检查是否漏引号",
            text[:40], max(0, tail - 20), tail)
    if text.count("《") != text.count("》"):
        add("error", "书名号《》不配对，请检查法规名称是否漏「》」", text[:40], max(0, tail - 20), tail)
    if text.count("（") != text.count("）"):
        add("warn", "圆括号（）不配对，请检查", text[:40], max(0, tail - 20), tail)

    # 5. 相邻书名号间的顿号（GB/T 15834：标有书名号的并列成分间通常不用顿号）
    for m in re.finditer(r"》\s*、\s*《", text):
        add("info", "《…》、《…》并列时书名号之间可不加顿号（GB/T 15834）", m.group(0), m.start(), m.end())

    # 6. 年月范围使用连字符
    for m in re.finditer(r"(\d+\s*[年月日])\s*[-–]\s*\d+", text):
        add("info", "时间范围建议使用一字线「—」，如“2024年—2025年”", m.group(0), m.start(), m.end())

    # 7. 段落结尾缺标点（仅对正文段落，跳过标题/短句/表格行）
    if is_paragraph:
        s = text.strip()
        if (len(s) >= 15 and not _HEADING_RE.match(s)
                and s[-1] not in _END_OK):
            add("warn", "段落结尾缺少标点（。；：等）", s[-20:], max(0, len(text) - 12), len(text))
    return items

